-- dss5105: shared PostgreSQL storage for the Python web and Telegram servers.
-- This creates empty tables. It does not connect either application or import data.
-- JSON payloads stay TEXT to preserve the existing Python serialization format.
-- Access is through trusted server-side database connections, not browser roles.
BEGIN;

CREATE TABLE IF NOT EXISTS public.allocations (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id TEXT NOT NULL UNIQUE,
    record TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.ledger_meta (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

INSERT INTO public.ledger_meta (key, value)
VALUES ('version', gen_random_uuid()::TEXT)
ON CONFLICT (key) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.performance (
    workshop_id TEXT PRIMARY KEY,
    samples TEXT NOT NULL,
    ratio DOUBLE PRECISION,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.api_usage (
    scope TEXT NOT NULL,
    at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS usage_scope_at ON public.api_usage (scope, at);

CREATE TABLE IF NOT EXISTS public.allocation_archive (
    archived_at TEXT NOT NULL,
    record TEXT NOT NULL
);

ALTER TABLE public.allocations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ledger_meta ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.performance ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.api_usage ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.allocation_archive ENABLE ROW LEVEL SECURITY;

COMMIT;

-- Verify the expected five tables and their access controls.
SELECT c.relname AS table_name, c.relrowsecurity AS rls_enabled
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public'
  AND c.relname IN ('allocations', 'ledger_meta', 'performance',
                   'api_usage', 'allocation_archive')
ORDER BY c.relname;
